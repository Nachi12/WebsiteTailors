import http from 'k6/http';
import { check } from 'k6';

export const options = {
  vus: 1,
  iterations: 1,
};

export default function () {
  const contactRes = http.get('http://127.0.0.1:8088/contact.php');
  const token = contactRes.html().find('input[name="csrf_token"]').attr('value');

  const payload = {
    csrf_token: token,
    name: 'Synthetic Load Test User',
    email: `synthetic_${Date.now()}@loadtest.local`,
    phone: '+91 9876543210',
    company: 'Synthetic Corp',
    service: 'Website Design',
    budget: '₹10,000 - ₹25,000',
    message: 'Valid automated test enquiry generated by k6',
    website_url: '',
  };

  const res = http.post('http://127.0.0.1:8088/api/contact.php', payload, {
    headers: { 'X-Requested-With': 'XMLHttpRequest' },
  });

  check(res, {
    'contact submit status 200': (r) => r.status === 200,
    'contact submit success true': (r) => {
      try {
        const body = JSON.parse(r.body);
        return body.success === true;
      } catch (e) {
        return false;
      }
    },
  });
}
